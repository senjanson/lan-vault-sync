import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { createRequire } from "module";
import { dirname, join } from "path";

const _require = createRequire(import.meta.url);

// Force ws package to use its Node.js entry point (index.js) instead of the
// browser stub (browser.js). esbuild 4.60+ with platform:"browser" respects
// the "browser" export condition in ws/package.json, which points to a stub
// that throws "ws does not work in the browser". We bypass this by resolving
// directly to the Node.js entry, which works correctly in Electron's renderer.
const wsNodePlugin = {
  name: "ws-node-resolve",
  setup(build) {
    build.onResolve({ filter: /^ws$/ }, () => {
      const pkgDir = dirname(_require.resolve("ws/package.json"));
      return { path: join(pkgDir, "index.js") };
    });
  },
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [wsNodePlugin],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  platform: "browser",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
